using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace SqlInterpol.Testing.Generators;

[Generator]
public class SqlTestSuiteGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var isEnabled = context.AnalyzerConfigOptionsProvider.Select(static (provider, _) =>
            provider.GlobalOptions.TryGetValue("build_property.GenerateConcreteTestSuites", out var value) &&
            string.Equals(value, "true", System.StringComparison.OrdinalIgnoreCase));

        var abstractSuites = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => IsAbstractTestSuiteBase(node),
                transform: static (ctx, _) => GetClassInfo(ctx))
            .Where(static info => info is not null);

        var input = abstractSuites.Combine(isEnabled);

        context.RegisterSourceOutput(input, static (spc, pair) =>
        {
            var (info, enabled) = pair;
            if (!enabled || info is null)
            {
                return;
            }

            // Strip "Base" suffix: PostgreSqlFromTestSuiteBase -> PostgreSqlFromTestSuite
            var concreteName = info.ClassName.Substring(0, info.ClassName.Length - 4);

            var source = $$"""
                // <auto-generated />
                #nullable enable

                namespace {{info.Namespace}};

                public class {{concreteName}} : {{info.ClassName}}
                {
                }
                """;

            spc.AddSource($"{concreteName}.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static bool IsAbstractTestSuiteBase(SyntaxNode node)
    {
        return node is ClassDeclarationSyntax classDecl &&
               classDecl.Identifier.Text.EndsWith("TestSuiteBase") &&
               classDecl.Modifiers.Any(SyntaxKind.AbstractKeyword);
    }

    private static ClassInfo? GetClassInfo(GeneratorSyntaxContext context)
    {
        var classDecl = (ClassDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(classDecl) is not INamedTypeSymbol symbol || !symbol.IsAbstract)
        {
            return null;
        }

        return new ClassInfo(
            symbol.ContainingNamespace.ToDisplayString(),
            symbol.Name);
    }

    private sealed record ClassInfo(string Namespace, string ClassName);
}